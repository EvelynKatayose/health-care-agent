// English assets are generated from the Chinese UI and a reviewed dictionary.
// Unknown UI copy fails the build, so the two versions cannot silently drift.
const fs=require('node:fs'),path=require('node:path'),ts=require('typescript');
const root=path.resolve(__dirname,'..');
const dictionary=JSON.parse(fs.readFileSync(path.join(__dirname,'english-translations.json'),'utf8'));
const hasHan=s=>/\p{Script=Han}/u.test(s);
function translate(text){
 if(!hasHan(text))return text;
 if(Object.hasOwn(dictionary,text))return dictionary[text];
 throw Error('Missing English translation: '+JSON.stringify(text));
}
function javascript(source){
 const tree=ts.createSourceFile('health.js',source,ts.ScriptTarget.Latest,true),edits=[];
 function visit(n){
  if(ts.isStringLiteral(n)||ts.isNoSubstitutionTemplateLiteral(n)){
   if(hasHan(n.text))edits.push({start:n.getStart(tree),end:n.end,text:JSON.stringify(translate(n.text))});
   else if(ts.isStringLiteral(n)&&n.text==='zh-CN')edits.push({start:n.getStart(tree),end:n.end,text:'"en-US"'});
  }else if((ts.isTemplateHead(n)||ts.isTemplateMiddle(n)||ts.isTemplateTail(n))&&hasHan(n.text)){
   edits.push({start:n.getStart(tree)+1,end:n.end-(ts.isTemplateTail(n)?1:2),text:translate(n.text).replace(/\\/g,'\\\\').replace(/`/g,'\\`').replace(/\$\{/g,'\\${')});
  }
  ts.forEachChild(n,visit);
 }
 visit(tree);
 for(const e of edits.sort((a,b)=>b.start-a.start))source=source.slice(0,e.start)+e.text+source.slice(e.end);
 source=source.replace('body:body!==undefined?JSON.stringify(body):undefined','body:body!==undefined?JSON.stringify({...body,language:"en"}):undefined')
  .replace('message:question,image:sentImage,','message:question,language:"en",image:sentImage,')
  .replace('d.error||','uiError(d.error)||').replace('error.error||','uiError(error.error)||')
  .replace('new Error(event.error)','new Error(uiError(event.error))')
  .replace('hint.title=s?`${s.detail}', 'hint.title=s?`${uiText(s.detail)}')
  .replace("statusFor(type)?.detail||", "uiError(statusFor(type)?.detail)||")
  .replace('n.notes+','uiText(n.notes)+')
  .replace('alert(d.message)','alert(uiText(d.message))');
 // These sentences need English word order rather than fragment substitution.
 source=source.replaceAll('summary.day+" days"','summary.day').replaceAll('label+"Score"','label+" score"')
  .replace("if(key==='average_breath')return n+\" bpm\";","if(key==='average_breath')return n+\" breaths/min\";");
 const runtime=`// Generated by scripts/build-english.cjs. Edit the source UI and dictionary instead.\nconst englishCopy=${JSON.stringify(dictionary)};\nfunction uiText(value){return typeof value==='string'?(englishCopy[value]??value):value;}\nfunction uiError(value){if(!value)return value;const translated=uiText(value);if(/\\p{Script=Han}/u.test(translated)){const http=translated.match(/HTTP \\d+/);return http?'The service returned '+http[0]+'. Please retry.':'The request could not be completed. Please check your input and try again.';}return translated;}\n`;
 return runtime+source;
}
const escapeText=s=>s.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
function html(source){
 source=source.replace(/>([^<>]*)</g,(all,text)=>{
  if(!hasHan(text))return all;
  const trimmed=text.trim(),leading=text.slice(0,text.indexOf(trimmed)),trailing=text.slice(text.indexOf(trimmed)+trimmed.length);
  return '>'+leading+escapeText(translate(trimmed))+trailing+'<';
 }).replace(/(aria-label|title|alt|placeholder|data-prompt)="([^"]*)"/g,(all,attr,value)=>hasHan(value)?attr+'="'+escapeText(translate(value)).replace(/"/g,'&quot;')+'"':all)
 .replace('lang="zh-CN"','lang="en"')
 .replaceAll('/health.html','/health-en.html')
 .replace('/health.js?v=8','/health-en.js?v=1')
 .replace('/manifest.webmanifest','/manifest-en.webmanifest')
 .replaceAll('href="/privacy/"','href="/privacy/en.html"')
 .replaceAll('href="/terms/"','href="/terms/en.html"')
 .replace('id="language-switch" href="/health-en.html?lang=en" lang="en">English</a>','id="language-switch" href="/health.html?lang=zh" lang="zh-CN">中文</a>');
 return '<!-- Generated from health.html by scripts/build-english.cjs. -->\n'+source;
}
if(require.main===module){
 fs.writeFileSync(path.join(root,'public/health-en.js'),javascript(fs.readFileSync(path.join(root,'public/health.js'),'utf8')));
 fs.writeFileSync(path.join(root,'public/health-en.html'),html(fs.readFileSync(path.join(root,'public/health.html'),'utf8')));
 const manifest=JSON.parse(fs.readFileSync(path.join(root,'public/manifest.webmanifest'),'utf8'));
 manifest.lang='en';manifest.start_url='/health-en.html?source=homescreen';
 fs.writeFileSync(path.join(root,'public/manifest-en.webmanifest'),JSON.stringify(manifest,null,2)+'\n');
 console.log('English interface generated.');
}
module.exports={translate,javascript,html};
